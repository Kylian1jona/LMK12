const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const account=fs.readFileSync('components/k12-account.js','utf8');
const progress=fs.readFileSync('components/k12-progress-ui.js','utf8');
const gateSource=account.match(/function gateAllowedSection\(sectionId\)\{[\s\S]*?(?=function applyAccessUI\()/)?.[0];
assert.ok(gateSource,'Access gate exists');
const context={loggedIn:true,currentPortalRole:'parent',currentAccountIsAdmin:false,subscriptionAccessAllowed:()=>false,anySubjectAllowed:()=>false,subjectAllowed:()=>false};
const gate=vm.runInNewContext(`${gateSource}\ngateAllowedSection`,context);
assert.equal(gate('parentPortal'),true);
assert.equal(gate('addUserPage'),true);
for(const section of ['home','grades','reading','playground','settings','lessonRunner','shop'])assert.equal(gate(section),false,`Parent cannot open ${section}`);
context.currentPortalRole='kid';
assert.equal(gate('playground'),true,'Playground is free for signed-in learners');
assert.equal(gate('grades'),false,'Lessons still follow plan access');
assert.equal(gate('parentPortal'),false,'Learners cannot open parent portal');
const unlock=progress.match(/function unlockPlayground\(\)\{[\s\S]*?\n\}/)?.[0];
assert.ok(unlock && !unlock.includes('state.learners') && unlock.includes('show("playground")'));
const dashboard=account.match(/async function renderParentPortal\(\)\{[\s\S]*?(?=\/\* ===========================\s*Paywall)/)?.[0]||'';
assert.ok(!dashboard.includes('Open learner')&&!dashboard.includes('Back to profiles'));
console.log('Parent and learner access checks passed; Playground does not spend Learners.');
