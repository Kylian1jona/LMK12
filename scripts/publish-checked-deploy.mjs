import fs from 'node:fs';
import path from 'node:path';
const siteId='c080ae32-3f93-4c0a-aabc-fae4b336fca8';
const [expected,preview]=process.argv.slice(2);
if(!expected||!preview)throw Error('Usage: node scripts/publish-checked-deploy.mjs <expected-live-id> <ready-preview-id>');
const config=JSON.parse(fs.readFileSync(path.join(process.env.APPDATA,'netlify','Config','config.json'),'utf8'));
const token=Object.values(config.users||{}).find(user=>user?.auth?.token)?.auth?.token;
if(!token)throw Error('Netlify token missing');
const headers={Authorization:`Bearer ${token}`};
const siteResponse=await fetch(`https://api.netlify.com/api/v1/sites/${siteId}`,{headers});
if(!siteResponse.ok)throw Error(`Site check failed: HTTP ${siteResponse.status}`);
const site=await siteResponse.json();
if(site.published_deploy?.id!==expected)throw Error(`Live deploy changed: ${site.published_deploy?.id}; expected ${expected}`);
const draftResponse=await fetch(`https://api.netlify.com/api/v1/deploys/${preview}`,{headers});
if(!draftResponse.ok)throw Error(`Preview check failed: HTTP ${draftResponse.status}`);
const draft=await draftResponse.json();
if(draft.state!=='ready'||draft.site_id!==siteId)throw Error('Preview is not ready for this site');
const response=await fetch(`https://api.netlify.com/api/v1/sites/${siteId}/deploys/${preview}/restore`,{method:'POST',headers});
const body=await response.json();
if(!response.ok)throw Error(`Publish failed: HTTP ${response.status} ${body.message||''}`);
console.log(JSON.stringify({id:body.id,state:body.state,live:body.deploy_ssl_url}));
